"""
Optimization Result Models.

Structured output generated by Module 06 after model building, solving, and validation.
"""

from __future__ import annotations

from typing import List, Dict, Optional, Any
from pydantic import BaseModel, ConfigDict, Field

from app.models.action_plan import ActionPlan
from app.models.constraint import ConstraintViolation


class MissionAllocationItem(BaseModel):
    """Allocation trajectory for a single mission."""
    mission_id: str
    mission_name: str
    priority: str
    time_step: int
    time_minutes: int
    allocated_power_kw: float
    is_active: bool
    cumulative_energy_kwh: float
    satisfied: bool


class StorageScheduleItem(BaseModel):
    """Storage trajectory for battery and hydrogen across time steps."""
    time_step: int
    time_minutes: int
    battery_charge_kw: float
    battery_discharge_kw: float
    battery_soc: float
    battery_energy_kwh: float
    hydrogen_charge_kw: float
    hydrogen_discharge_kw: float
    hydrogen_energy_kwh: float


class ReserveTrajectoryItem(BaseModel):
    """Reserve trajectory across time steps compared against M07 thresholds."""
    time_step: int
    time_minutes: int
    projected_stored_energy_kwh: float
    required_reserve_kwh: float
    protected_energy_kwh: float
    margin_kwh: float
    reserve_met: bool


class OptimizationResult(BaseModel):
    """Complete Output Payload for Module 06 Optimization."""
    model_config = ConfigDict(protected_namespaces=())

    optimization_id: str
    station_id: str
    created_at: str
    horizon_minutes: int
    time_step_minutes: int
    solve_time_seconds: float = 0.0
    objective_value: float = 0.0
    solver: str = "ortools"
    solver_status: str = "FEASIBLE"  # OPTIMAL, FEASIBLE, INFEASIBLE, TIMEOUT, ERROR
    feasible: bool = True
    validation_passed: bool = True
    
    constraint_summary: Dict[str, int] = Field(default_factory=dict)  # total, satisfied, violated
    violations: List[ConstraintViolation] = Field(default_factory=list)

    mission_allocations: List[MissionAllocationItem] = Field(default_factory=list)
    storage_schedule: List[StorageScheduleItem] = Field(default_factory=list)
    generation_schedule: List[Dict[str, float]] = Field(default_factory=list)
    curtailment: List[float] = Field(default_factory=list)
    reserve_trajectory: List[ReserveTrajectoryItem] = Field(default_factory=list)
    
    scenario: str = "BASELINE"
    objective_breakdown: Dict[str, float] = Field(default_factory=dict)
    warnings: List[str] = Field(default_factory=list)
    explanations: List[str] = Field(default_factory=list)
    
    action_plan: Optional[ActionPlan] = None
    infeasibility_report: Optional[Dict[str, Any]] = None
    model_version: str = "1.0.0"
